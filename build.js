#!/usr/bin/env node

/**
 * Build script for Nuvio KissAsian Provider
 * Bundles ES modules from src/ into standalone providers/ compatible with Hermes & React Native.
 */

const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const srcDir = path.join(__dirname, 'src');
const outDir = path.join(__dirname, 'providers');

const PROVIDERS = [
  { name: 'kissasian', entry: path.join(srcDir, 'kissasian', 'index.js') }
];

async function buildProvider(provider) {
  const outFile = path.join(outDir, `${provider.name}.js`);

  try {
    await esbuild.build({
      entryPoints: [provider.entry],
      bundle: true,
      outfile: outFile,
      format: 'cjs',
      platform: 'neutral',
      target: 'es2016', // Lowers async/await to generators for Hermes compatibility
      minify: false,
      sourcemap: false,
      banner: {
        js: `/**\n * ${provider.name} - Nuvio Streaming Provider\n * Auto-generated by esbuild targeting Hermes (ES2016)\n */`
      }
    });

    const stats = fs.statSync(outFile);
    console.log(`✔ [BUILD SUCCESS] ${provider.name}.js (${(stats.size / 1024).toFixed(2)} KB) -> ${outFile}`);
  } catch (err) {
    console.error(`✖ [BUILD FAILED] ${provider.name}:`, err.message);
    process.exit(1);
  }
}

async function main() {
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  console.log('⚡ Building Nuvio Provider bundle (Hermes ES2016 target)...\n');
  for (const provider of PROVIDERS) {
    await buildProvider(provider);
  }
  console.log('\n✨ Build complete.');
}

main();
